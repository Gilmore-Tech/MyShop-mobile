/// Corner radii used across the MyShop design system.
///
/// Update a value here to retheme every surface/button that honours the
/// design system in one place.
abstract final class MyShopRadius {
  /// Primary button radius. 10 per the current brand spec.
  static const double button = 10;

  /// Card radius — used on vehicle option cards, recent destination cards,
  /// fare breakdown, etc.
  static const double card = 12;

  /// Input field radius — pickup/destination inputs, search fields, stops.
  static const double input = 10;

  /// Pill / chip radius.
  static const double pill = 20;
}
